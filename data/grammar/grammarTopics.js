function buildGrammarTopics() {
  const allTopics = [];

  for (let sourceIndex = 0; sourceIndex < grammarSources.length; sourceIndex++) {
    const source = grammarSources[sourceIndex];

    for (let topicIndex = 0; topicIndex < source.topics.length; topicIndex++) {
      const topic = source.topics[topicIndex];

      allTopics.push({
        id: source.id + "-" + topic.id,
        sourceId: source.id,
        sourceTitle: source.title,
        categoryId: source.categoryId,
        categoryTitle: source.categoryTitle,
        title: topic.title,
        subtitle: source.title + " | " + topic.subtitle,
        explanation: topic.explanation,
        examples: topic.examples
      });
    }
  }

  return allTopics;
}

export const grammarTopics = buildGrammarTopics();
